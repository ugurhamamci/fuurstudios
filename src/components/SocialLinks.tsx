/**
 * Panelden girilen sosyal medya ayarlarını link listesine çevirir.
 * Boş bırakılan hesaplar listeye hiç girmez, böylece sitede ölü "#" linki kalmaz.
 */
export const buildSocialLinks = (settings: Record<string, string>): SocialLink[] => {
  const waNumber = (settings.whatsappNumber || '').replace(/[^0-9]/g, '');

  const candidates: { key: string; label: string; href: string }[] = [
    { key: 'instagram', label: 'Instagram', href: settings.instagram_url || '' },
    { key: 'whatsapp', label: 'WhatsApp', href: waNumber ? `https://wa.me/${waNumber}` : '' },
    { key: 'linkedin', label: 'LinkedIn', href: settings.linkedin_url || '' },
    { key: 'twitter', label: 'X (Twitter)', href: settings.twitter_url || '' },
    { key: 'facebook', label: 'Facebook', href: settings.facebook_url || '' },
    { key: 'youtube', label: 'YouTube', href: settings.youtube_url || '' },
    { key: 'github', label: 'GitHub', href: settings.github_url || '' },
  ];

  return candidates
    .filter((c) => c.href.trim() !== '')
    .map((c) => ({ ...c, href: c.href.trim(), icon: icons[c.key] }));
};

export default function SocialLinks({
  links,
  style,
  className = 'social-links',
}: {
  links: SocialLink[];
  style?: CSSProperties;
  className?: string;
}) {
  if (links.length === 0) return null;

  return (
    <div className={className} style={style}>
      {links.map((link) => (
        <a
          key={link.key}
          href={link.href}
          target="_blank"
          rel="noopener noreferrer"
          className="social-link"
          aria-label={link.label}
        >
          {link.icon}
        </a>
      ))}
    </div>
  );
}
